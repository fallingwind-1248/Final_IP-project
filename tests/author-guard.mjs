import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {spawnSync} from 'node:child_process';
import assert from 'node:assert/strict';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const temp=path.join(root,'.local','author-guard-'+Date.now());
fs.mkdirSync(path.join(temp,'scripts'),{recursive:true});fs.mkdirSync(path.join(temp,'src'));
fs.copyFileSync(path.join(root,'scripts/project.mjs'),path.join(temp,'scripts/project.mjs'));
const original=fs.readFileSync(path.join(root,'src/story.twee'),'utf8');
const source=path.join(temp,'src/story.twee');fs.writeFileSync(source,original);
const run=action=>spawnSync(process.execPath,[path.join(temp,'scripts/project.mjs'),action],{encoding:'utf8',windowsHide:true});
assert.equal(run('checkpoint').status,0);
fs.writeFileSync(source,original+'\n/* Technical stylesheet comment for the guard test. */\n');
assert.equal(run('compare').status,0,'Technical-only edits preserve author text');
fs.writeFileSync(source,original.replace('This is a placeholder for a short reading passage.','Author text changed by the guard test.'));
const denied=run('compare');assert.equal(denied.status,1);assert.match(denied.stderr,/TextShort/);
fs.writeFileSync(source,original);assert.equal(run('compare').status,0);
const result={checkedAt:new Date().toISOString(),status:'passed',cases:['technical-only edit accepted','author-text edit detected and failed','original author text accepted'],productionSourceModified:false};
fs.writeFileSync(path.join(root,'evidence/tests/author-guard-regression.json'),JSON.stringify(result,null,2)+'\n');
console.log('Author text guard regression passed.');
